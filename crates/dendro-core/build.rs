//! Species registry: every `data/species/*.ron` file is embedded at compile
//! time (`include_str!`), so adding a species is adding a file, and the
//! exported game and the tests see exactly the same genomes (determinism).
//!
//! Generates `$OUT_DIR/species_registry.rs`:
//! `pub(crate) const SPECIES_FILES: &[(&str, &str)] = &[(id, ron), ...];`
//! sorted by file name (`read_dir` order is not portable). The id is the
//! file stem (`picea_abies` for `picea_abies.ron`).

use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let dir = manifest.join("../../data/species");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut files: Vec<(String, PathBuf)> = std::fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("species directory {}: {e}", dir.display()))
        .filter_map(|e| e.ok())
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|x| x == "ron"))
        .map(|p| (p.file_stem().unwrap().to_string_lossy().into_owned(), p))
        .collect();
    files.sort();
    let mut out = String::from("/// Embedded species files `(id, RON text)`, sorted by id (generated by build.rs).\n");
    out.push_str("pub(crate) const SPECIES_FILES: &[(&str, &str)] = &[\n");
    for (id, path) in &files {
        assert!(
            !id.is_empty() && id.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_'),
            "species file name {id:?}: use lowercase latin_name.ron ([a-z0-9_])"
        );
        println!("cargo:rerun-if-changed={}", path.display());
        // Absolute (manifest-based) path; `{:?}` escapes the backslashes of
        // Windows paths. No `canonicalize`: it yields `\\?\` paths there.
        writeln!(out, "    ({id:?}, include_str!({:?})),", path.to_string_lossy()).unwrap();
    }
    out.push_str("];\n");
    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("species_registry.rs");
    std::fs::write(dest, out).expect("write species_registry.rs");
}
